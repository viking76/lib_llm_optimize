"""Agent 0 — Evaluator.

The library runs the evaluation itself: give it a question set (the user's
own dataset) and the model under test, and it asks every question, scores
the answers, and feeds the results straight into the 4-agent pipeline.

Scoring is pluggable; two scorers ship built-in:

- :func:`exact_match` — normalized string equality (default).
- :func:`contains_match` — expected answer contained in the model answer
  (useful for generative models that pad their answers).
"""

from __future__ import annotations

import json
import re
from typing import Callable, List, Optional, Sequence

from .model_adapter import ModelAdapter
from .types import EvalResult, Question

Scorer = Callable[[str, str], float]


def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip().lower())


def exact_match(model_answer: str, expected: str) -> float:
    return 1.0 if _normalize(model_answer) == _normalize(expected) else 0.0


def contains_match(model_answer: str, expected: str) -> float:
    return 1.0 if _normalize(expected) in _normalize(model_answer) else 0.0


def load_questions(path: str) -> List[Question]:
    """Load a user question set from JSONL.

    Rows: {"id"?, "text", "expected_answer", "category"?}. Missing ids are
    autogenerated as q-<index>.
    """
    questions: List[Question] = []
    with open(path, "r", encoding="utf-8") as fh:
        for index, line in enumerate(fh):
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            questions.append(
                Question(
                    id=str(row.get("id", f"q-{index}")),
                    text=str(row["text"]),
                    expected_answer=str(row["expected_answer"]),
                    category=row.get("category", "general"),
                    metadata=row.get("metadata", {}),
                )
            )
    return questions


class Evaluator:
    def __init__(
        self,
        model: ModelAdapter,
        scorer: Optional[Scorer] = None,
        pass_threshold: float = 0.5,
    ) -> None:
        self.model = model
        self.scorer = scorer or exact_match
        self.pass_threshold = pass_threshold

    def evaluate(self, questions: Sequence[Question]) -> List[EvalResult]:
        results: List[EvalResult] = []
        for question in questions:
            answer = self.model.answer(question)
            score = float(self.scorer(answer, question.expected_answer))
            results.append(
                EvalResult(
                    question_id=question.id,
                    model_answer=answer,
                    expected_answer=question.expected_answer,
                    passed=score >= self.pass_threshold,
                    score=score,
                    category=question.category,
                )
            )
        return results
